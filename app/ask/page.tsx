'use client';

// Ask the data: questions go to a Cortex Agent that writes SQL with Cortex Analyst over COMPLAINTS_SV.
// The answer streams in; the semantic view and the generated SQL are listed as its sources.
import { MessagesSquare, Send } from 'lucide-react';
import { useState } from 'react';
import { LogoMark } from '@/components/Brand';
import { Reasoning } from '@/components/Reasoning';
import { ErrorBox } from '@/components/Status';
import { Card, Docket, Markdown, PoweredBy, SampleAiBadge, SourceBadge, Sources, useStream } from '@/components/ui';
import { data } from '@/lib/client';
import { SUGGESTED_QUESTIONS } from '@/lib/ci-data';
import type { Answer } from '@/lib/types';

function AnswerCard({ a }: { a: Answer }) {
  const { shown, done } = useStream(a.text || 'The agent returned no text.');
  return (
    <div className="flex gap-3 fade-up">
      <div className="shrink-0 mt-1"><LogoMark size={26} /></div>
      <div className="card p-4 flex-1 min-w-0">
        <div className="flex gap-2 flex-wrap items-center mb-2">{a.source === 'mock' && <SampleAiBadge />}<SourceBadge p={a} />{a.tools.map((t) => <span key={t} className="pill" style={{ background: 'var(--paper-2)', color: 'var(--ink-2)' }}>{t}</span>)}</div>
        <Markdown text={shown + (done && a.sql ? ' [1]' : '')} caret={!done} />
        {done && <Sources items={[{ label: 'COMPLAINTS_SV semantic view', detail: 'queried by Cortex Analyst' }]} />}
        {done && a.sql && <details className="mt-2"><summary className="text-xs font-semibold cursor-pointer" style={{ color: 'var(--signal)' }}>SQL generated by Cortex Analyst</summary>
          <pre className="text-xs rounded-lg p-3 mt-2 overflow-x-auto" style={{ background: 'var(--paper-2)' }}>{a.sql}</pre></details>}
      </div>
    </div>
  );
}

export default function AskPage() {
  const [q, setQ] = useState('');
  const [busy, setBusy] = useState<string>();
  const [items, setItems] = useState<(Answer | { question: string; error: string })[]>([]);
  const ask = async (question: string) => {
    if (!question.trim() || busy) return;
    setBusy(question); setQ('');
    try { const a = await data.ask(question); setItems((x) => [a, ...x]); }
    catch (e) { setItems((x) => [{ question, error: String((e as Error).message) }, ...x]); }
    finally { setBusy(undefined); }
  };
  return (
    <div className="space-y-5 max-w-4xl">
      <Docket eyebrow="Analyst assistant" title="Ask the complaints data" right={<><PoweredBy>Cortex Agents</PoweredBy><PoweredBy>Cortex Analyst</PoweredBy></>}>
        Ask about volumes, themes, flags and deadlines in plain English. The agent answers from the semantic view and never quotes complaint text.
      </Docket>
      <Card>
        <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); ask(q); }}>
          <label className="sr-only" htmlFor="q">Question</label>
          <input id="q" className="input flex-1 !py-2.5 !text-sm" value={q} onChange={(e) => setQ(e.target.value)} placeholder="How many open complaints are overdue, by product?" />
          <button className="btn btn-primary" disabled={!!busy || !q.trim()} aria-label="Ask"><Send className="w-4 h-4" aria-hidden />Ask</button>
        </form>
        <div className="eyebrow mt-4 mb-2">Try one</div>
        <div className="grid sm:grid-cols-2 gap-2">
          {SUGGESTED_QUESTIONS.map((s) => <button key={s} className="btn btn-ai text-xs !text-left !justify-start !whitespace-normal" disabled={!!busy} onClick={() => ask(s)}><MessagesSquare className="w-3.5 h-3.5 shrink-0" aria-hidden />{s}</button>)}
        </div>
      </Card>
      {busy && (
        <div className="space-y-3">
          <div className="flex justify-end"><div className="rounded-xl px-3.5 py-2 text-sm max-w-[80%]" style={{ background: 'var(--brand)', color: 'var(--on-brand)' }}>{busy}</div></div>
          <Reasoning kind="ask" />
        </div>
      )}
      {items.map((a, i) => (
        <div key={items.length - i} className="space-y-3">
          <div className="flex justify-end"><div className="rounded-xl px-3.5 py-2 text-sm max-w-[80%]" style={{ background: 'var(--brand)', color: 'var(--on-brand)' }}>{a.question}</div></div>
          {'error' in a ? <ErrorBox error={a.error} /> : <AnswerCard a={a} />}
        </div>
      ))}
      {!items.length && !busy && <p className="text-sm muted text-center py-6">Answers appear here, newest first.</p>}
    </div>
  );
}
