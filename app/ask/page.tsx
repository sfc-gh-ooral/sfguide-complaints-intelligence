'use client';

// Ask the data: questions go to a Cortex Agent that writes SQL with Cortex Analyst over COMPLAINTS_SV.
import { Send } from 'lucide-react';
import { useState } from 'react';
import { Reasoning } from '@/components/Reasoning';
import { ErrorBox } from '@/components/Status';
import { Card, Markdown, PoweredBy, SampleAiBadge, SourceBadge } from '@/components/ui';
import { data } from '@/lib/client';
import { SUGGESTED_QUESTIONS } from '@/lib/ci-data';
import type { Answer } from '@/lib/types';

export default function AskPage() {
  const [q, setQ] = useState('');
  const [busy, setBusy] = useState(false);
  const [items, setItems] = useState<(Answer | { question: string; error: string })[]>([]);
  const ask = async (question: string) => {
    if (!question.trim() || busy) return;
    setBusy(true); setQ('');
    try { const a = await data.ask(question); setItems((x) => [a, ...x]); }
    catch (e) { setItems((x) => [{ question, error: String((e as Error).message) }, ...x]); }
    finally { setBusy(false); }
  };
  return (
    <div className="space-y-4">
      <div className="flex items-start justify-between gap-3 flex-wrap">
        <div>
          <h1 className="text-xl font-semibold">Ask the data</h1>
          <p className="text-sm text-2 mt-1">Ask about volumes, themes, flags, and deadlines. The agent never quotes complaint text.</p>
        </div>
        <PoweredBy>Cortex Agents + Cortex Analyst</PoweredBy>
      </div>
      <Card>
        <form className="flex gap-2" onSubmit={(e) => { e.preventDefault(); ask(q); }}>
          <label className="sr-only" htmlFor="q">Question</label>
          <input id="q" className="input flex-1" value={q} onChange={(e) => setQ(e.target.value)} placeholder="How many open complaints are overdue, by product?" />
          <button className="btn btn-primary" disabled={busy || !q.trim()} aria-label="Ask"><Send className="w-4 h-4" /></button>
        </form>
        <div className="flex flex-wrap gap-2 mt-3">
          {SUGGESTED_QUESTIONS.map((s) => <button key={s} className="btn btn-ai text-xs text-left" disabled={busy} onClick={() => ask(s)}>{s}</button>)}
        </div>
      </Card>
      {busy && <Reasoning kind="ask" />}
      {items.map((a, i) => (
        <Card key={i} title={a.question} right={'error' in a ? undefined : <>{a.source === 'mock' && <SampleAiBadge />}<SourceBadge p={a} /></>}>
          {'error' in a ? <ErrorBox error={a.error} /> : (
            <>
              <Markdown text={a.text || 'The agent returned no text.'} />
              {a.sql && <details className="mt-3"><summary className="text-xs muted cursor-pointer">SQL generated by Cortex Analyst</summary>
                <pre className="text-xs rounded-lg p-3 mt-2 overflow-x-auto" style={{ background: 'var(--surface-2)' }}>{a.sql}</pre></details>}
            </>
          )}
        </Card>
      ))}
    </div>
  );
}
